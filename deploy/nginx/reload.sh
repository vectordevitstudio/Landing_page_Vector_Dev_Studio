#!/bin/sh
# Запускается из /docker-entrypoint.d ДО старта nginx (поэтому только ставит
# фоновый цикл и сразу возвращает управление).
#
# Раз в 6 ч перечитываем конфиг nginx, чтобы подхватить TLS-сертификат,
# который контейнер certbot продлевает в фоне.
( while :; do
    sleep 21600
    nginx -s reload 2>/dev/null || true
  done ) &
